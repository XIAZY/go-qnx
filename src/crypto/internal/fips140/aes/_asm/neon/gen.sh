# gen.sh writes the NEON assembly for GOARCH=arm, aes_arm.s and
# gcm/gcm_arm.s, from OpenSSL's perlasm modules. Go's arm assembler has
# no NEON instructions, so each module is assembled with clang and its
# instructions are written out as WORDs, with the disassembly beside
# them. Only OpenSSL's inner functions are used: they keep to R0-R6 and
# R12 and use no stack, so they need nothing from the C calling
# convention. What surrounds them is written here, for Go's.
#
# It also writes vendor/golang.org/x/crypto/chacha20/chacha_arm.s, which
# is not from OpenSSL: its NEON ChaCha20 runs a fourth block in the
# integer registers, all of them, and keeps its state on the stack. Here
# three blocks go through the plain quarter-round side by side, in NEON
# registers alone.
#
#	gen.sh <openssl source directory>
#
# The files in the tree were made from the tag openssl-3.5.0. It needs
# perl, a clang that can target ARM, and LLVM's objdump.

set -eu

ossl=$1
aes=$(cd "$(dirname "$0")/../.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

as() {
	clang -target armv7a-linux-gnueabi -I"$ossl/crypto" -D__ARM_MAX_ARCH__=7 -c "$1" -o "$2"
}

# words prints the instructions of function $2 in object file $1 as
# WORD lines, up to but not including its first "bx lr". With $3, it
# starts at the first instruction of that name instead of the first.
words() {
	objdump -d "$1" | awk -v sym="<$2>:" -v from="${3-}" '
		$2 == sym { on = 1; next }
		!on || NF < 3 || $1 !~ /:$/ { next }
		$3 == "bx" { exit }
		from != "" { if ($3 != from) next; from = "" }
		{
			w = $2
			$1 = $2 = ""
			sub(/^ +/, "")
			sub(/ *@ imm.*$/, "")
			sub(/ 0x[0-9a-f]+ </, " <")
			printf "\tWORD $0x%s // %s\n", w, $0
		}'
}

# neon prints its arguments, one instruction each, as WORD lines.
neon() {
	{
		printf '.arch armv7-a\n.fpu neon\nneon:\n'
		printf '\t%s\n' "$@"
	} >"$tmp/neon.S"
	as "$tmp/neon.S" "$tmp/neon.o"
	words "$tmp/neon.o" neon
}

# consts prints OpenSSL's _bsaes_const table as DATA lines.
consts() {
	awk '
		/^_bsaes_const:/ { on = 1; next }
		/\.asciz/ { on = 0 }
		!on { next }
		/^\.L/ { sub(/:.*/, "", $1); printf "// %s, at %d\n", $1, off }
		/\.quad/ {
			gsub(/,/, " ")
			for (i = 2; i <= 3; i++) {
				printf "DATA bsaesConst<>+%d(SB)/4, $0x%s\n", off, substr($i, 11, 8)
				printf "DATA bsaesConst<>+%d(SB)/4, $0x%s\n", off + 4, substr($i, 3, 8)
				off += 8
			}
		}' "$1"
}

header() {
	cat <<EOF
// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by $1. DO NOT EDIT.

//go:build !purego

// The NEON instructions below are from OpenSSL's
// $2, which carries the following comment:
// # ====================================================================
// # Written by Andy Polyakov <appro@openssl.org> for the OpenSSL
// # project. The module is, however, dual licensed under OpenSSL and
// # CRYPTOGAMS licenses depending on where you obtain it. For further
// # details see http://www.openssl.org/~appro/cryptogams/.
EOF
}

perl "$ossl/crypto/modes/asm/ghash-armv4.pl" void "$tmp/ghash.S"
as "$tmp/ghash.S" "$tmp/ghash.o"

{
	header ../_asm/neon/gen.sh crypto/modes/asm/ghash-armv4.pl
	cat <<EOF
// # ====================================================================
//
// Go's assembler has no NEON instructions, so they are given as words.
// The functions are gcm_init_neon and gcm_ghash_neon. They use R0-R3,
// Q0-Q3, Q8-Q11 and Q13-Q15, and no stack.

#include "textflag.h"

// func gcmInitNEON(htable *[16]byte, h *[2]uint64)
TEXT ·gcmInitNEON(SB),NOSPLIT|NOFRAME,\$0-8
	MOVW htable+0(FP), R0
	MOVW h+4(FP), R1
$(words "$tmp/ghash.o" gcm_init_neon)
	RET

// func gcmGhashNEON(xi, htable *[16]byte, data []byte)
TEXT ·gcmGhashNEON(SB),NOSPLIT|NOFRAME,\$0-20
	MOVW xi+0(FP), R0
	MOVW htable+4(FP), R1
	MOVW data_base+8(FP), R2
	MOVW data_len+12(FP), R3
$(words "$tmp/ghash.o" gcm_ghash_neon)
	RET
EOF
} >"$aes/gcm/gcm_arm.s"

perl "$ossl/crypto/aes/asm/bsaes-armv7.pl" void "$tmp/bsaes.S"
as "$tmp/bsaes.S" "$tmp/bsaes.o"

{
	header _asm/neon/gen.sh crypto/aes/asm/bsaes-armv7.pl
	cat <<EOF
// #
// # Specific modes and adaptation for Linux kernel by Ard Biesheuvel
// # of Linaro.
// # ====================================================================
//
// Go's assembler has no NEON instructions, so they are given as words.
// Of the module, only _bsaes_key_convert, _bsaes_encrypt8 and
// _bsaes_decrypt8 are here, which use R4-R6, R12 and Q0-Q15, and no stack.
// They find the module's constants from their own address; here R6 is set
// by the caller.

#include "textflag.h"

$(consts "$tmp/bsaes.S")
GLOBL bsaesConst<>(SB), RODATA|NOPTR, \$128

// func bsaesKeyConvertNEON(dst *byte, enc *uint32, rounds int)
//
// It writes round key 0 as it is, the round keys 1 to rounds-1 bit-sliced,
// 128 bytes each, and the last round key XORed with 0x63 in each byte.
TEXT ·bsaesKeyConvertNEON(SB),NOSPLIT|NOFRAME,\$0-12
	MOVW dst+0(FP), R12
	MOVW enc+4(FP), R4
	MOVW rounds+8(FP), R5
	MOVW \$bsaesConst<>+96(SB), R6 // .LM0
$(neon 'vld1.8 {q7}, [r4]!' 'vld1.8 {q15}, [r4]!')
$(words "$tmp/bsaes.o" _bsaes_key_convert vmov.i8)
$(neon 'veor q7, q7, q15' 'vstmia r12, {q7}')
	RET

// bsaesEncrypt8 is _bsaes_encrypt8_alt. It encrypts the eight blocks in
// Q0-Q7 and leaves them in Q0, Q1, Q4, Q6, Q3, Q7, Q2 and Q5, in that order.
// R4 points to the second round key of a schedule from bsaesKeyConvertNEON
// and Q9 holds the first, R5 holds the number of rounds, Q8 holds .LM0SR
// and R6 points to .LSR. It changes R4-R6 and Q8-Q15.
TEXT bsaesEncrypt8<>(SB),NOSPLIT|NOFRAME,\$0-0
$(words "$tmp/bsaes.o" _bsaes_encrypt8_alt)
	RET

// func xorKeyStream8NEON(bs *byte, rounds int, dst, src, counters *[128]byte)
TEXT ·xorKeyStream8NEON(SB),NOSPLIT,\$0-20
	MOVW bs+0(FP), R4
	MOVW rounds+4(FP), R5
	MOVW counters+16(FP), R0
	MOVW \$bsaesConst<>+48(SB), R6 // .LM0SR
$(neon 'vld1.8 {q0-q1}, [r0]!' 'vld1.8 {q2-q3}, [r0]!' \
	'vld1.8 {q4-q5}, [r0]!' 'vld1.8 {q6-q7}, [r0]' \
	'vldmia r4!, {q9}' 'vldmia r6!, {q8}')
	BL bsaesEncrypt8<>(SB)
	MOVW src+12(FP), R0
	MOVW dst+8(FP), R1
	// All of src is read before any of dst is written, so they may be
	// the same memory.
$(neon 'vld1.8 {q8-q9}, [r0]!' 'vld1.8 {q10-q11}, [r0]!' \
	'vld1.8 {q12-q13}, [r0]!' 'vld1.8 {q14-q15}, [r0]' \
	'veor q0, q0, q8' 'veor q1, q1, q9' 'veor q4, q4, q10' 'veor q6, q6, q11' \
	'veor q3, q3, q12' 'veor q7, q7, q13' 'veor q2, q2, q14' 'veor q5, q5, q15' \
	'vst1.8 {q0-q1}, [r1]!' 'vst1.8 {q4}, [r1]!' 'vst1.8 {q6}, [r1]!' \
	'vst1.8 {q3}, [r1]!' 'vst1.8 {q7}, [r1]!' 'vst1.8 {q2}, [r1]!' \
	'vst1.8 {q5}, [r1]')
	RET

// bsaesDecrypt8 is _bsaes_decrypt8 from its first veor. It decrypts the
// eight blocks in Q0-Q7 and leaves them in Q0, Q1, Q6, Q4, Q2, Q7, Q3 and
// Q5, in that order. R4 points to the second round key of a schedule that
// bsaesKeyConvertNEON made from the decryption round keys, with the 0x63
// moved from its last round key to its first, and Q9 holds the first. R5
// holds the number of rounds, Q8 holds .LM0ISR and R6 points to .LISR. It
// changes R4-R6 and Q8-Q15.
TEXT bsaesDecrypt8<>(SB),NOSPLIT|NOFRAME,\$0-0
$(words "$tmp/bsaes.o" _bsaes_decrypt8 veor)
	RET

// func cbcDecrypt8NEON(bs *byte, rounds int, dst, src *[128]byte, iv *[16]byte)
//
// It is .Lcbc_dec_loop of the module's bsaes_cbc_encrypt, once around.
TEXT ·cbcDecrypt8NEON(SB),NOSPLIT,\$0-20
	MOVW bs+0(FP), R4
	MOVW rounds+4(FP), R5
	MOVW src+12(FP), R0
	MOVW \$bsaesConst<>+0(SB), R6 // .LM0ISR
$(neon 'vld1.8 {q0-q1}, [r0]!' 'vld1.8 {q2-q3}, [r0]!' \
	'vld1.8 {q4-q5}, [r0]!' 'vld1.8 {q6-q7}, [r0]' \
	'vldmia r4!, {q9}' 'vldmia r6!, {q8}')
	BL bsaesDecrypt8<>(SB)
	MOVW src+12(FP), R0
	MOVW dst+8(FP), R1
	MOVW iv+16(FP), R2
	// All of src is read before any of dst is written, so they may be
	// the same memory.
$(neon 'vld1.8 {q14}, [r2]' 'vld1.8 {q8-q9}, [r0]!' 'veor q0, q0, q14' \
	'vld1.8 {q10-q11}, [r0]!' 'veor q1, q1, q8' 'veor q6, q6, q9' \
	'vld1.8 {q12-q13}, [r0]!' 'veor q4, q4, q10' 'veor q2, q2, q11' \
	'vld1.8 {q14-q15}, [r0]' 'veor q7, q7, q12' 'veor q3, q3, q13' \
	'veor q5, q5, q14' 'vst1.8 {q15}, [r2]' \
	'vst1.8 {q0-q1}, [r1]!' 'vst1.8 {q6}, [r1]!' 'vst1.8 {q4}, [r1]!' \
	'vst1.8 {q2}, [r1]!' 'vst1.8 {q7}, [r1]!' 'vst1.8 {q3}, [r1]!' \
	'vst1.8 {q5}, [r1]')
	RET
EOF
} >"$aes/aes_arm.s"

# three prints each line of its input three times, once for each of three
# ChaCha20 blocks: A, B, C and D become the block's rows and T its scratch
# register.
three() {
	while read -r line; do
		for regs in 'q0 q1 q2 q3 q12' 'q4 q5 q6 q7 q13' 'q8 q9 q10 q11 q14'; do
			set -- $regs
			echo "$line" | sed "s/A/$1/g; s/B/$2/g; s/C/$3/g; s/D/$4/g; s/T/$5/g"
		done
	done
}

# The quarter-round, on a block's four columns at once.
qr=$(three <<'EOF'
vadd.i32 A, A, B
veor D, D, A
vrev32.16 D, D
vadd.i32 C, C, D
veor T, B, C
vshr.u32 B, T, #20
vsli.32 B, T, #12
vadd.i32 A, A, B
veor T, D, A
vshr.u32 D, T, #24
vsli.32 D, T, #8
vadd.i32 C, C, D
veor T, B, C
vshr.u32 B, T, #25
vsli.32 B, T, #7
EOF
)

{
	cat <<'EOF'
.arch armv7-a
.fpu neon
chacha:
	vld1.32 {q0-q1}, [r2]
	add r3, r2, #32
	vld1.32 {q2-q3}, [r3]
	vmov.i32 q15, #0
	mov r3, #1
	vmov.32 d30[0], r3
	vmov q4, q0
	vmov q5, q1
	vmov q6, q2
	vadd.i32 q7, q3, q15
	vmov q8, q0
	vmov q9, q1
	vmov q10, q2
	vadd.i32 q11, q7, q15
	mov r3, #10
1:
EOF
	echo "$qr"
	# Turn the rows so that the diagonals stand in the columns, and back.
	three <<'EOF'
vext.8 B, B, B, #4
vext.8 C, C, C, #8
vext.8 D, D, D, #12
EOF
	echo "$qr"
	three <<'EOF'
vext.8 B, B, B, #12
vext.8 C, C, C, #8
vext.8 D, D, D, #4
EOF
	cat <<'EOF'
	subs r3, r3, #1
	bne 1b
	vld1.32 {q12-q13}, [r2]!
	vld1.32 {q14}, [r2]!
	vadd.i32 q0, q0, q12
	vadd.i32 q4, q4, q12
	vadd.i32 q8, q8, q12
	vadd.i32 q1, q1, q13
	vadd.i32 q5, q5, q13
	vadd.i32 q9, q9, q13
	vadd.i32 q2, q2, q14
	vadd.i32 q6, q6, q14
	vadd.i32 q10, q10, q14
	vld1.32 {q12}, [r2]
	vadd.i32 q3, q3, q12
	vadd.i32 q12, q12, q15
	vadd.i32 q7, q7, q12
	vadd.i32 q12, q12, q15
	vadd.i32 q11, q11, q12
	vld1.8 {q12-q13}, [r1]!
	vld1.8 {q14-q15}, [r1]!
	veor q0, q0, q12
	veor q1, q1, q13
	veor q2, q2, q14
	veor q3, q3, q15
	vst1.8 {q0-q1}, [r0]!
	vst1.8 {q2-q3}, [r0]!
	vld1.8 {q12-q13}, [r1]!
	vld1.8 {q14-q15}, [r1]!
	veor q4, q4, q12
	veor q5, q5, q13
	veor q6, q6, q14
	veor q7, q7, q15
	vst1.8 {q4-q5}, [r0]!
	vst1.8 {q6-q7}, [r0]!
	vld1.8 {q12-q13}, [r1]!
	vld1.8 {q14-q15}, [r1]
	veor q8, q8, q12
	veor q9, q9, q13
	veor q10, q10, q14
	veor q11, q11, q15
	vst1.8 {q8-q9}, [r0]!
	vst1.8 {q10-q11}, [r0]
EOF
} >"$tmp/chacha.S"
as "$tmp/chacha.S" "$tmp/chacha.o"

cat >"$aes/../../../../vendor/golang.org/x/crypto/chacha20/chacha_arm.s" <<EOF
// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by crypto/internal/fips140/aes/_asm/neon/gen.sh. DO NOT EDIT.

//go:build gc && !purego

// Go's assembler has no NEON instructions, so they are given as words.
// Three blocks are computed side by side. The rows of the first are in
// Q0-Q3, of the second in Q4-Q7 and of the third in Q8-Q11, so that a
// quarter-round works on the four columns of a block at once. Q12-Q14
// are scratch and Q15 holds the 1 that is added to the block counter.

#include "textflag.h"

// func xorKeyStream3NEON(dst, src *[192]byte, state *[16]uint32)
TEXT ·xorKeyStream3NEON(SB),NOSPLIT|NOFRAME,\$0-12
	MOVW dst+0(FP), R0
	MOVW src+4(FP), R1
	MOVW state+8(FP), R2
$(words "$tmp/chacha.o" chacha)
	RET
EOF
