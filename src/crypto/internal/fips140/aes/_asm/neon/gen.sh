# k512 prints OpenSSL's K512 table as DATA lines, low word first.
k512() {
	awk '
		/^K512:/ { on = 1; next }
		!on { next }
		/^WORD64\(/ {
			gsub(/WORD64\(|\)|,/, " ")
			for (i = 1; i <= 3; i += 2) {
				printf "DATA k512<>+%d(SB)/4, $0x%s\n", off, substr($(i+1), 3, 8)
				printf "DATA k512<>+%d(SB)/4, $0x%s\n", off + 4, substr($i, 3, 8)
				off += 8
			}
			next
		}
		on && off { exit }' "$1"
}

