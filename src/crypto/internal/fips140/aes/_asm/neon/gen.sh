// Go's assembler has no NEON instructions, so they are given as words.
// Three blocks are computed side by side. The rows of the first are in
// Q0-Q3, of the second in Q4-Q7 and of the third in Q8-Q11, so that a
// quarter-round works on the four columns of a block at once. Q12-Q14
// are scratch and Q15 holds the 1 that is added to the block counter.

#include "textflag.h"

// func xorKeyStream3NEON(dst, src *[192]byte, state *[16]uint32)
TEXT ·xorKeyStream3NEON(SB),NOSPLIT|NOFRAME,\$0-12
	MOVW dst+0(FP), R0
	MOVW src+4(FP), R1
	MOVW state+8(FP), R2
$(words "$tmp/chacha.o" chacha)
	RET
EOF

# Poly1305, two blocks at a time, one in each 32-bit lane of D registers,
# in limbs of 26 bits. D10-D14 are the accumulators h0-h4, D0-D4 the
# multiplier's limbs r0-r4 and D5-D8 five times r1-r4. Each time around,
# the two blocks are added to the accumulators and the sums multiplied by
# the multiplier, into Q8-Q12, and the carries are passed on as in "NEON
# crypto" by Bernstein and Schwabe, which leaves limbs a little over 26
# bits.
cat >"$tmp/poly.S" <<'EOF'
.arch armv7-a
.fpu neon
poly:
	vld1.32 {d0-d3}, [r1]!
	vld1.32 {d4-d7}, [r1]!
	vld1.32 {d8}, [r1]
	add r12, r0, #32
	vld1.32 {d10-d13}, [r0]
	vld1.32 {d14}, [r12]
	vmov.i64 q15, #0xffffffff
	vshr.u64 q15, q15, #6
1:
	vld4.32 {d26, d27, d28, d29}, [r2]!
	vmov d9, d26
	vbic.i32 d9, #0xfc000000
	vadd.i32 d10, d10, d9
	vshr.u32 d9, d26, #26
	vsli.32 d9, d27, #6
	vbic.i32 d9, #0xfc000000
	vadd.i32 d11, d11, d9
	vshr.u32 d9, d27, #20
	vsli.32 d9, d28, #12
	vbic.i32 d9, #0xfc000000
	vadd.i32 d12, d12, d9
	vshr.u32 d9, d28, #14
	vsli.32 d9, d29, #18
	vbic.i32 d9, #0xfc000000
	vadd.i32 d13, d13, d9
	vshr.u32 d9, d29, #8
	vorr.i32 d9, #0x01000000
	vadd.i32 d14, d14, d9
	vmull.u32 q8, d10, d0
	vmlal.u32 q8, d11, d8
	vmlal.u32 q8, d12, d7
	vmlal.u32 q8, d13, d6
	vmlal.u32 q8, d14, d5
	vmull.u32 q9, d10, d1
	vmlal.u32 q9, d11, d0
	vmlal.u32 q9, d12, d8
	vmlal.u32 q9, d13, d7
	vmlal.u32 q9, d14, d6
	vmull.u32 q10, d10, d2
	vmlal.u32 q10, d11, d1
	vmlal.u32 q10, d12, d0
	vmlal.u32 q10, d13, d8
	vmlal.u32 q10, d14, d7
	vmull.u32 q11, d10, d3
	vmlal.u32 q11, d11, d2
	vmlal.u32 q11, d12, d1
	vmlal.u32 q11, d13, d0
	vmlal.u32 q11, d14, d8
	vmull.u32 q12, d10, d4
	vmlal.u32 q12, d11, d3
	vmlal.u32 q12, d12, d2
	vmlal.u32 q12, d13, d1
	vmlal.u32 q12, d14, d0
	vshr.u64 q13, q11, #26
	vand q11, q11, q15
	vadd.i64 q12, q12, q13
	vshr.u64 q13, q8, #26
	vand q8, q8, q15
	vadd.i64 q9, q9, q13
	vshr.u64 q13, q12, #26
	vand q12, q12, q15
	vshl.i64 q14, q13, #2
	vadd.i64 q8, q8, q13
	vadd.i64 q8, q8, q14
	vshr.u64 q13, q9, #26
	vand q9, q9, q15
	vadd.i64 q10, q10, q13
	vshr.u64 q13, q10, #26
	vand q10, q10, q15
	vadd.i64 q11, q11, q13
	vshr.u64 q13, q8, #26
	vand q8, q8, q15
	vadd.i64 q9, q9, q13
	vshr.u64 q13, q11, #26
	vand q11, q11, q15
	vadd.i64 q12, q12, q13
	vmovn.i64 d10, q8
	vmovn.i64 d11, q9
	vmovn.i64 d12, q10
	vmovn.i64 d13, q11
	vmovn.i64 d14, q12
	subs r3, r3, #1
	bne 1b
	vst1.32 {d10-d13}, [r0]
	vst1.32 {d14}, [r12]
EOF
as "$tmp/poly.S" "$tmp/poly.o"

