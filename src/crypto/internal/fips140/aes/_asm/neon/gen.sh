// Go's assembler has no NEON instructions, so they are given as words.
// Of the module, only sha512_block_data_order_neon is here, from where it
// loads the context. It uses R0-R3, R12 and D0-D31, and no stack. It finds
// K512 from its own address; here R3 is set by the caller. Its vpush and
// vpop of D8-D15 are left out, as Go has no registers to save.

#include "textflag.h"

$(k512 "$tmp/sha512.S")
GLOBL k512<>(SB), RODATA|NOPTR, \$640

// func blockNEON(dig *Digest, p []byte)
//
// The words are in a function of their own: a constant here would make
// the assembler put a pool among them, which the branches would not skip.
TEXT ·blockNEON(SB),NOSPLIT,\$0-16
	MOVW dig+0(FP), R0
	MOVW p_base+4(FP), R1
	MOVW p_len+8(FP), R2
	BIC \$127, R2
	ADD R1, R2 // the end of the whole blocks
	CMP R1, R2
	BEQ done
	MOVW \$k512<>(SB), R3
	BL block<>(SB)
done:
	RET

// block is sha512_block_data_order_neon, from its vldmia. R0 points to the
// context, R1 to the input and R2 to its end, and R3 to K512.
TEXT block<>(SB),NOSPLIT|NOFRAME,\$0-0
$(words "$tmp/sha512.o" sha512_block_data_order_neon vldmia | grep -v " // vpop ")
	RET
EOF
} >"$aes/../sha512/sha512block_arm.s"

# SHA-256 with the message schedule in NEON, for ../sha256. The rounds
# are those of sha256block_arm.s, in the integer registers; the schedule
# is computed four words at a time in Q0-Q3, as OpenSSL's sha256-armv4.pl
# and others do, and each word goes to the stack with its constant added.
# OpenSSL's own function is not used: it keeps the working variables in
# R4-R11, and R10 and R11 are Go's.
sha256=$(cd "$aes/../sha256" && pwd)

# k256 prints the constants of sha256block.go as DATA lines.
k256() {
	grep -o '0x[0-9a-f]\{8\},' "$sha256/sha256block.go" | head -n 64 |
		awk '{ sub(/,/, ""); printf "DATA k256<>+%d(SB)/4, $%s\n", 4 * (NR - 1), $1 }'
}

# rounds prints the four rounds that start at round $1. Each round takes
# the working variables one place further round.
rounds() {
	r=$1
	while [ "$r" -lt $(($1 + 4)) ]; do
		set -- "$1" R1 R2 R3 R4 R5 R6 R7 R8
		n=$((r % 8))
		while [ "$n" -gt 0 ]; do
			set -- "$1" "$9" "$2" "$3" "$4" "$5" "$6" "$7" "$8"
			n=$((n - 1))
		done
		printf '\tROUND(%d, %s, %s, %s, %s, %s, %s, %s, %s)\n' "$r" "$2" "$3" "$4" "$5" "$6" "$7" "$8" "$9"
		r=$((r + 1))
	done
}

# schedule prints the NEON code that makes w[$1+16] to w[$1+19] from the
# sixteen words before them, which are in Q$2, Q$3, Q$4 and Q$5 in that
# order, leaves them in Q$2, and stores them with their constants added.
# R14 points to the constants and R12 to where the words go.
schedule() {
	a=$2 b=$3 c=$4 d=$5
	alo=$((2 * a)) ahi=$((2 * a + 1)) dhi=$((2 * d + 1))
	neon "vext.8 q8, q$a, q$b, #4" "vext.8 q9, q$c, q$d, #4" \
		'vshr.u32 q10, q8, #7' 'vsli.32 q10, q8, #25' \
		'vshr.u32 q11, q8, #18' 'vsli.32 q11, q8, #14' \
		'vshr.u32 q8, q8, #3' 'veor q8, q8, q10' 'veor q8, q8, q11' \
		"vadd.i32 q$a, q$a, q9" "vadd.i32 q$a, q$a, q8" \
		"vshr.u32 d24, d$dhi, #17" "vsli.32 d24, d$dhi, #15" \
		"vshr.u32 d25, d$dhi, #19" "vsli.32 d25, d$dhi, #13" \
		"vshr.u32 d26, d$dhi, #10" 'veor d24, d24, d25' 'veor d24, d24, d26' \
		"vadd.i32 d$alo, d$alo, d24" \
		"vshr.u32 d24, d$alo, #17" "vsli.32 d24, d$alo, #15" \
		"vshr.u32 d25, d$alo, #19" "vsli.32 d25, d$alo, #13" \
		"vshr.u32 d26, d$alo, #10" 'veor d24, d24, d25' 'veor d24, d24, d26' \
		"vadd.i32 d$ahi, d$ahi, d24" \
		'vld1.32 {q8}, [r14]' "vadd.i32 q8, q8, q$a" 'vst1.32 {q8}, [r12]'
}

{
	cat <<EOF
// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by ../aes/_asm/neon/gen.sh. DO NOT EDIT.

//go:build !purego

#include "textflag.h"

// SHA-256 with the message schedule in NEON. Go's assembler has no NEON
// instructions, so they are given as words.
//
// The rounds are those of sha256block_arm.s: the working variables stay in
// R1-R8, and R0, R12 and R14 are scratch. Q0-Q3 hold the last sixteen
// words of the schedule. Every four rounds the next four words are made
// from them, as in OpenSSL's sha256-armv4.pl, and each goes to the ring of
// sixteen on the stack with its constant already added, which is where
// the rounds read it. Q8-Q13 are scratch.

$(k256)
GLOBL k256<>(SB), RODATA|NOPTR, \$256

// The frame: the ring, then the data pointer and the end of the data.
#define WK(i)	(4+4*((i)&15))(R13)
#define p_data	68(R13)
#define p_end	72(R13)

// See sha256block_arm.s; here R0 is set to w[i] + k.
#define ROUND(i, a, b, c, d, e, f, g, h) \\
	MOVW	WK(i), R0; \\
	ADD	R0, h; \\
	EOR	e@>5, e, R0; \\
	EOR	e@>19, R0; \\
	EOR	f, g, R12; \\
	ADD	R0@>6, h; \\
	AND	e, R12; \\
	EOR	g, R12; \\
	ADD	R12, h; \\
	EOR	a@>11, a, R0; \\
	ADD	h, d; \\
	EOR	a@>20, R0; \\
	EOR	a, b, R12; \\
	EOR	b, c, R14; \\
	ADD	R0@>2, h; \\
	AND	R14, R12; \\
	EOR	b, R12; \\
	ADD	R12, h

// func blockNEON(dig *Digest, p []byte)
TEXT ·blockNEON(SB), 0, \$72-16
	MOVW	p_base+4(FP), R0
	MOVW	p_len+8(FP), R12
	BIC	\$63, R12
	ADD	R0, R12
	CMP	R0, R12
	BEQ	done
	MOVW	R12, p_end

	MOVW	dig+0(FP), R14
	MOVW	0(R14), R1
	MOVW	4(R14), R2
	MOVW	8(R14), R3
	MOVW	12(R14), R4
	MOVW	16(R14), R5
	MOVW	20(R14), R6
	MOVW	24(R14), R7
	MOVW	28(R14), R8

loop:
	// The sixteen words of the block, with R0 pointing to it.
	MOVW	\$k256<>(SB), R14
	MOVW	\$WK(0), R12
$(neon 'vld1.8 {q0-q1}, [r0]!' 'vld1.8 {q2-q3}, [r0]!' \
	'vrev32.8 q0, q0' 'vrev32.8 q1, q1' 'vrev32.8 q2, q2' 'vrev32.8 q3, q3' \
	'vld1.32 {q8-q9}, [r14]!' 'vld1.32 {q10-q11}, [r14]' \
	'vadd.i32 q8, q8, q0' 'vadd.i32 q9, q9, q1' \
	'vadd.i32 q10, q10, q2' 'vadd.i32 q11, q11, q3' \
	'vst1.32 {q8-q9}, [r12]!' 'vst1.32 {q10-q11}, [r12]')
	MOVW	R0, p_data

EOF
	i=0
	while [ "$i" -lt 48 ]; do
		rounds "$i"
		printf '\tMOVW\t$k256<>+%d(SB), R14\n\tMOVW\t$WK(%d), R12\n' $((4 * (i + 16))) "$i"
		t=$((i / 4))
		schedule "$i" $((t % 4)) $(((t + 1) % 4)) $(((t + 2) % 4)) $(((t + 3) % 4))
		echo
		i=$((i + 4))
	done
	while [ "$i" -lt 64 ]; do
		rounds "$i"
		i=$((i + 4))
	done
	cat <<EOF

	MOVW	dig+0(FP), R14
EOF
	for j in 0 1 2 3 4 5 6 7; do
		printf '\tMOVW\t%d(R14), R0\n\tADD\tR0, R%d\n\tMOVW\tR%d, %d(R14)\n' $((4 * j)) $((j + 1)) $((j + 1)) $((4 * j))
	done
	cat <<EOF

	MOVW	p_data, R0
	MOVW	p_end, R12
	CMP	R0, R12
	BNE	loop

done:
	RET
EOF
} >"$sha256/sha256block_neon_arm.s"
